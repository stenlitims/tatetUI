<script setup lang="ts">
/**
 * Оформлення вмісту: те саме і в редакторі, і на публічній сторінці.
 *
 * Компонент навмисно майже порожній — уся цінність у `ui-prose.css`, який
 * він підключає своїм класом. UiRichTextEditor ставить РІВНО той самий клас
 * на корінь ProseMirror, тож редактор і читалка не можуть роз'їхатись: це і
 * є WYSIWYG за побудовою, а не за домовленістю.
 */

withDefaults(
  defineProps<{
    /**
     * HTML як рядок — типовий випадок для вмісту з бази чи редактора.
     *
     * Вставляється через `v-html` і НЕ санітизується: компонент не має
     * власного санітайзера і не вдає, що має. Джерело HTML — ваша
     * відповідальність, і чистити його треба на сервері.
     */
    html?: string | null
    /** Кореневий тег. `article` для самостійного матеріалу, `div` для фрагмента. */
    as?: 'div' | 'article' | 'section'
  }>(),
  { as: 'div' },
)

defineSlots<{
  /** Вміст як розмітка Vue — альтернатива пропу `html`. */
  default?: () => unknown
}>()
</script>

<template>
  <!-- v-html і слот взаємовиключні: якщо задано html, слот ігнорується.
       HTML вставляється ПРЯМО в корінь з класом ui-prose, без обгортки:
       зайвий <div> між класом і блоками вмісту вимикав правила з `>`
       (останній блок лишався з нижнім відступом), і той самий HTML
       виглядав інакше, ніж у редакторі, — клас багів docs-prose. -->
  <component :is="as" v-if="html != null" class="ui-prose" v-html="html" />
  <component :is="as" v-else class="ui-prose">
    <slot />
  </component>
</template>
