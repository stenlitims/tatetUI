/**
 * Токенізація української для MiniSearch.
 *
 * Типовий токенізатор MiniSearch розриває слово на апострофі:
 *   "м'який"  → ["м", "який"]
 *   "об'єкт"  → ["об", "єкт"]
 *   "зв'язок" → ["зв", "язок"]
 *
 * Наслідок не в тому, що слово не знайдеться, а в шумі: запит «м'який»
 * починає збігатися з усім, де є «який», а документ зі словом «Ім'я»
 * індексується уламком «я», який збігається майже з будь-чим.
 *
 * Тут апостроф вважається частиною слова — розривають лише пробіли та
 * пунктуація.
 */

/** Усі варіанти апострофа, що трапляються в українських текстах. */
const APOSTROPHES = /['\u2019\u02BC\u201B\u00B4`]/g

/** Межа слова: усе, що не літера, не цифра і не апостроф. */
const SEPARATORS = /[^\p{L}\p{N}'\u2019\u02BC]+/u

export function tokenize(text: string): string[] {
  return text.split(SEPARATORS).filter(Boolean)
}

/**
 * Нормалізація терма.
 *
 * Апостроф прибирається ПІСЛЯ токенізації, а не до: так «м'який» і
 * «мякий» (частий друк без апострофа) зводяться до одного терма, але саме
 * слово при цьому не розпадається надвоє.
 */
export function processTerm(term: string): string | null {
  const normalized = term.toLowerCase().replace(APOSTROPHES, '')
  // Однолітерні уламки лише шумлять у результатах.
  return normalized.length > 1 ? normalized : null
}
